#!/usr/bin/env python3
"""Regenerate the release file table in verify.html from a GitHub release.

    python3 site/update-verify.py v0.1.4

Needs the GitHub CLI (`gh`), signed in. Downloads the release's `.sha256`
files, checks each one against the SHA-256 GitHub computed for the uploaded
file, and rewrites the block between the `release-files` markers in
verify.html. Fails without changing anything if a checksum file is malformed
or disagrees with GitHub.
"""

import argparse
import datetime
import html
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

PAGE = Path(__file__).resolve().parent / "verify.html"
BEGIN = "<!-- release-files: generated by update-verify.py, do not edit by hand -->"
END = "<!-- /release-files -->"
HEX64 = re.compile(r"[0-9a-f]{64}")


def gh(*args):
    result = subprocess.run(["gh", *args], capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args)} failed:\n{result.stderr.strip()}")
    return result.stdout


def read_checksums(tag, repo):
    """Map each file name to the hash its `.sha256` file states."""
    sums = {}
    with tempfile.TemporaryDirectory() as tmp:
        gh("release", "download", tag, "--repo", repo, "-p", "*.sha256", "-D", tmp)
        for path in sorted(Path(tmp).glob("*.sha256")):
            # `sha256sum` writes "<hash>  <name>"; the Windows build writes
            # "<hash> *<name>", the binary mode marker.
            line = path.read_text(encoding="utf-8").strip()
            parts = line.split(maxsplit=1)
            if len(parts) != 2 or not HEX64.fullmatch(parts[0].lower()):
                sys.exit(f"{path.name}: not a SHA-256 line: {line!r}")
            digest, name = parts[0].lower(), parts[1].lstrip("*")
            if name != path.name.removesuffix(".sha256"):
                sys.exit(f"{path.name}: names {name!r}, expected {path.name.removesuffix('.sha256')!r}")
            sums[name] = digest
    if not sums:
        sys.exit(f"{tag}: the release has no .sha256 files")
    return sums


def os_order(name):
    """Windows, then macOS, then Linux, the order the home page uses."""
    lower = name.lower()
    if "windows" in lower or lower.endswith((".exe", ".msi")):
        return 0
    if "macos" in lower or lower.endswith(".dmg"):
        return 1
    return 2


def render(tag, repo, release, sums):
    version = tag.removeprefix("v")
    published = datetime.datetime.fromisoformat(release["publishedAt"].replace("Z", "+00:00"))
    date = f"{published.day} {published:%B %Y}"
    base = f"https://github.com/{repo}/releases"
    rows = []
    for name in sorted(sums, key=lambda n: (os_order(n), n.lower())):
        digest = sums[name]
        n = html.escape(name)
        rows.append(
            f'<tr><th scope="row"><a href="{base}/download/{html.escape(tag)}/{n}">{n}</a></th>'
            f'<td data-label="SHA-256"><code>{digest}</code></td>'
            f'<td data-label="VirusTotal"><a href="https://www.virustotal.com/gui/file/{digest}"'
            f' aria-label="VirusTotal report for {n}">Report</a></td></tr>'
        )
    return "\n".join(
        [
            BEGIN,
            f'<p>HatchZip <a href="{base}/tag/{html.escape(tag)}">{html.escape(version)}</a>, published {date}.</p>',
            '<table class="stack hashes">',
            "<thead>",
            '<tr><th scope="col">File</th><th scope="col">SHA-256</th><th scope="col">VirusTotal</th></tr>',
            "</thead>",
            "<tbody>",
            *rows,
            "</tbody>",
            "</table>",
            END,
        ]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("tag", help="release tag, such as v0.1.4")
    parser.add_argument("--repo", default="xevrion/hatchzip")
    args = parser.parse_args()

    release = json.loads(
        gh("release", "view", args.tag, "--repo", args.repo, "--json", "publishedAt,assets")
    )
    assets = {a["name"]: a for a in release["assets"]}
    sums = read_checksums(args.tag, args.repo)

    for name, digest in sums.items():
        if name not in assets:
            sys.exit(f"{name}.sha256 has no matching file in the release")
        github = (assets[name].get("digest") or "").removeprefix("sha256:")
        if not github:
            print(f"warning: GitHub reports no digest for {name}; using the .sha256 file alone")
        elif github != digest:
            sys.exit(f"{name}: the .sha256 file says {digest}, GitHub computed {github}")
    for name in sorted(assets):
        if not name.endswith(".sha256") and name not in sums:
            print(f"warning: {name} has no .sha256 file and is left out of the table")

    page = PAGE.read_text(encoding="utf-8")
    start, end = page.find(BEGIN), page.find(END)
    if start < 0 or end < start:
        sys.exit(f"{PAGE}: the release-files markers are missing")
    updated = page[:start] + render(args.tag, args.repo, release, sums) + page[end + len(END):]
    if updated == page:
        print(f"{PAGE.name} already lists {args.tag}")
        return
    PAGE.write_text(updated, encoding="utf-8")
    print(f"{PAGE.name}: {len(sums)} files from {args.tag}")


if __name__ == "__main__":
    main()
